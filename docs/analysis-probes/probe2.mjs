const ROOT = 'file:///D:/codes/ai/AgentBox/agent-control-center-claude';
const { EventBus, Orchestrator } = await import(`${ROOT}/packages/core/src/index.ts`);
const { InMemoryControlPlaneStore } = await import(`${ROOT}/packages/storage/src/index.ts`);
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));
const src = await import('./probe-agent.mjs');
const claude = new src.AsyncAgent('claude', 'claude', { fallback: { kind: 'reply' }, syncTurn: true });
const codex = new src.AsyncAgent('codex', 'codex', { syncTurn: true });
const test = new src.AsyncAgent('test', 'test', { fallback: { kind: 'test', passed: true }, syncTurn: true });
const store = new InMemoryControlPlaneStore();
const orch = new Orchestrator(store, new EventBus());
for (const a of [claude, codex, test]) orch.registerAdapter(a);
const task = await orch.createTask({ title: 't', prompt: 'p', agentId: 'claude', budget: { maxStallCount: 1 }, testCommand: 'npm test' });
await sleep(50);
console.log('LOG1', JSON.stringify(claude.log));
const ev1 = await store.listEvents(task.runId);
console.log(ev1.map((e) => `${e.sequence}:${e.type}:${e.agentId ?? ''}:${e.data.status ?? e.data.step ?? ''}`).join('\n'));
const n = ev1.length;
await orch.resolveGate(task.id, 'retry', 'again');
await sleep(100);
console.log('LOG2', JSON.stringify(claude.log));
const ev2 = await store.listEvents(task.runId);
console.log(ev2.slice(n).map((e) => `${e.sequence}:${e.type}:${e.agentId ?? ''}:${e.data.status ?? ''}:${e.data.step ?? ''}`).join('\n'));
const run = await store.getRun(task.runId);
console.log('FINAL', run.status, run.workflowState.step, run.workflowState.awaitingAgentId, run.budget.agentCallsUsed);
